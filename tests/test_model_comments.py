"""Engine-style `*` comment lines in the shared INI reader `model.parse`.

Contract: research/notes/delivery/ini-star-comment.md (R1-R2). The engine reader
(properties.f90 `prop_inifile_pointer`) treats a line whose first non-blank
character is `*` as a comment, like `#`.
"""
from __future__ import annotations

import hashlib
import tempfile
import unittest
from pathlib import Path

from dfm_cli import model
from dfm_cli.common import DfmError

BOM = b"\xef\xbb\xbf"
BASE = b"[time]\nStartDateTime = 20000101000000\n[output]\nHisInterval = 600\nMapInterval = 1200\n"


def signature(records):
    return [(e.address, e.value, e.line, e.start, e.end) for e in records]


def insert(raw: bytes, marker: bytes, text: bytes) -> bytes:
    """Return raw with the line `text` inserted directly before the first `marker`."""
    index = raw.index(marker)
    return raw[:index] + text + raw[index:]


class StarCommentParseTests(unittest.TestCase):
    def assert_comment_equivalent(self, plain: bytes, starred: bytes, inserted_at: int, inserted_len: int, lines_before: int):
        old, new = model.parse(plain), model.parse(starred)
        self.assertEqual(len(old), len(new))
        for before, after in zip(old, new):
            self.assertEqual((before.address, before.value), (after.address, after.value))
            shift = inserted_len if before.start >= inserted_at else 0
            self.assertEqual(before.start + shift, after.start)
            self.assertEqual(before.end + shift, after.end)
            self.assertEqual(starred[after.start:after.end].decode("utf-8"), after.value)
            self.assertEqual(before.line + (1 if before.line > lines_before else 0), after.line)

    def test_star_line_at_file_start(self):
        line = b"* generated by the GUI\n"
        self.assert_comment_equivalent(BASE, line + BASE, 0, len(line), 0)

    def test_star_line_at_file_start_after_bom(self):
        line = b"* generated by the GUI\n"
        self.assert_comment_equivalent(BOM + BASE, BOM + line + BASE, len(BOM), len(line), 0)

    def test_star_line_after_section_header(self):
        line = b"* a note\n"
        marker = b"StartDateTime"
        self.assert_comment_equivalent(BASE, insert(BASE, marker, line), BASE.index(marker), len(line), 1)

    def test_star_line_between_keys(self):
        line = b"* between keys\n"
        marker = b"MapInterval"
        self.assert_comment_equivalent(BASE, insert(BASE, marker, line), BASE.index(marker), len(line), 4)

    def test_star_line_before_a_section_header(self):
        line = b"* before section\n"
        marker = b"[output]"
        self.assert_comment_equivalent(BASE, insert(BASE, marker, line), BASE.index(marker), len(line), 2)

    def test_indented_star_lines(self):
        for prefix in (b"  ", b"\t", b" \t "):
            with self.subTest(prefix=prefix):
                line = prefix + b"* indented note\n"
                marker = b"HisInterval"
                self.assert_comment_equivalent(BASE, insert(BASE, marker, line), BASE.index(marker), len(line), 3)

    def test_star_line_with_crlf_endings(self):
        plain = BASE.replace(b"\n", b"\r\n")
        line = b"* crlf note\r\n"
        marker = b"HisInterval"
        self.assert_comment_equivalent(plain, insert(plain, marker, line), plain.index(marker), len(line), 3)

    def test_star_line_without_trailing_newline_at_end(self):
        starred = BASE + b"* last line, no newline"
        old, new = model.parse(BASE), model.parse(starred)
        self.assertEqual(signature(old), signature(new))

    def test_star_line_with_key_value_or_section_text_stays_a_comment(self):
        for text in (b"* Key = value\n", b"*[section]\n", b"*key=1 # trailing\n", b"**\n", b"*\n", b"* \n"):
            with self.subTest(text=text):
                starred = insert(BASE, b"MapInterval", text)
                self.assertEqual([(e.address, e.value) for e in model.parse(BASE)],
                                 [(e.address, e.value) for e in model.parse(starred)])

    def test_star_line_in_file_that_only_has_a_comment_before_entries(self):
        starred = b"*\n* header\n" + BASE
        self.assertEqual([(e.address, e.value) for e in model.parse(BASE)],
                         [(e.address, e.value) for e in model.parse(starred)])

    def test_star_inside_key_or_value_keeps_its_meaning(self):
        raw = b"[output]\nx*=1\nkey = *value\nother = 5 * 2\n"
        entries = {e.address: e.value for e in model.parse(raw)}
        self.assertEqual(entries, {"output/x*": "1", "output/key": "*value", "output/other": "5 * 2"})

    def test_star_after_equals_or_indent_inside_a_value_line_is_not_a_comment_line(self):
        raw = b"[output]\n  key=*\nlast = 1\n"
        entries = {e.address: e.value for e in model.parse(raw)}
        self.assertEqual(entries, {"output/key": "*", "output/last": "1"})

    def test_other_malformed_lines_still_raise_syntax_error(self):
        for text in (b"garbage line\n", b"x * y\n"):
            with self.subTest(text=text):
                with self.assertRaises(DfmError) as caught:
                    model.parse(insert(BASE, b"MapInterval", text))
                self.assertEqual(caught.exception.code, "syntax_error")

    def test_semicolon_and_hash_comments_unchanged(self):
        raw = BASE + b"; semicolon note\n# hash note\n  ; indented semicolon\n"
        self.assertEqual(signature(model.parse(BASE)), signature(model.parse(raw)))

    def test_file_with_only_star_lines_has_no_entries(self):
        with self.assertRaises(DfmError) as caught:
            model.parse(b"* only a comment\n")
        self.assertEqual(caught.exception.code, "syntax_error")


class StarCommentEditTests(unittest.TestCase):
    def test_in_place_edit_preserves_star_lines_byte_for_byte(self):
        raw = (BOM + b"* header comment\r\n[time]\r\n\t* tab note\r\nStartDateTime = 20000101000000\r\n"
               b"[output]\r\n  * spaced note\r\nHisInterval = 600 # keep\r\n* between\r\nMapInterval = 1200\r\n* tail")
        with tempfile.TemporaryDirectory() as directory:
            path = Path(directory) / "model.mdu"
            path.write_bytes(raw)
            preview = model.edit(path, "output/hisinterval", "60", False, None)
            self.assertEqual(path.read_bytes(), raw)
            self.assertEqual(preview["before_sha256"], hashlib.sha256(raw).hexdigest())
            model.edit(path, "output/hisinterval", "60", True, preview["before_sha256"])
            expected = raw.replace(b"HisInterval = 600 # keep", b"HisInterval = 60 # keep")
            self.assertNotEqual(expected, raw)
            self.assertEqual(path.read_bytes(), expected)

    def test_edit_of_a_key_after_star_line_uses_correct_offset(self):
        raw = BASE.replace(b"MapInterval", b"* note that shifts offsets\nMapInterval")
        with tempfile.TemporaryDirectory() as directory:
            path = Path(directory) / "model.mdu"
            path.write_bytes(raw)
            preview = model.edit(path, "output/mapinterval", "300", False, None)
            model.edit(path, "output/mapinterval", "300", True, preview["before_sha256"])
            self.assertEqual(path.read_bytes(), raw.replace(b"MapInterval = 1200", b"MapInterval = 300"))

    def test_mdu_class_reads_star_commented_file(self):
        raw = b"* GUI header\n" + BASE
        with tempfile.TemporaryDirectory() as directory:
            path = Path(directory) / "model.mdu"
            path.write_bytes(raw)
            mdu = model.Mdu(path)
            self.assertEqual(mdu.get("output/hisinterval"), "600")
            self.assertEqual(mdu.get("time/startdatetime"), "20000101000000")


if __name__ == "__main__":
    unittest.main()
